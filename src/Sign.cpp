Sign::Sign(float x, float y, const std::string& text, const Color& color)
    : GameObject(x, y, (CHAR_WIDTH + CHAR_SPACING) * text.length() * 6, CHAR_HEIGHT * 6, color)
    , m_text(text) {
    // Convert text to uppercase for the sign
    std::transform(m_text.begin(), m_text.end(), m_text.begin(), ::toupper);
}

void Sign::update(float deltaTime) {
    if (m_effectEnabled) {
        m_effectTime += deltaTime * m_effectSpeed;
    }
}

void Sign::render(SDL_Renderer* renderer) const {
    if (m_text.empty()) return;
    
    float x = m_x - m_cameraOffsetX;
    float y = m_y - m_cameraOffsetY;
    
    // Calculate total width and height of the sign
    float totalWidth = m_text.length() * (CHAR_WIDTH + CHAR_SPACING) * m_scale;
    float totalHeight = (CHAR_HEIGHT + 2) * m_scale;
    
    // Draw outer border (dark)
    SDL_SetRenderDrawColor(renderer, 40, 40, 80, 200);
    SDL_FRect outerBorder = {x - 15, y - 15, totalWidth + 30, totalHeight + 30};
    SDL_RenderFillRectF(renderer, &outerBorder);
    
    // Draw inner border (lighter)
    SDL_SetRenderDrawColor(renderer, 80, 80, 150, 220);
    SDL_FRect innerBorder = {x - 10, y - 10, totalWidth + 20, totalHeight + 20};
    SDL_RenderFillRectF(renderer, &innerBorder);
    
    // Draw gradient background
    for (int i = 0; i < totalHeight + 10; i++) {
        float ratio = static_cast<float>(i) / (totalHeight + 10);
        SDL_SetRenderDrawColor(renderer, 
                              static_cast<Uint8>(20 + ratio * 40), 
                              static_cast<Uint8>(20 + ratio * 30), 
                              static_cast<Uint8>(60 + ratio * 40), 
                              230);
        SDL_RenderDrawLineF(renderer, x - 5, y - 5 + i, x + totalWidth + 5, y - 5 + i);
    }
    
    // Draw pixel decorations
    SDL_SetRenderDrawColor(renderer, 255, 255, 100, 100);
    for (int i = 0; i < 4; i++) {
        // Top-left corner decoration
        SDL_RenderDrawPointF(renderer, x - 12 + i, y - 12);
        SDL_RenderDrawPointF(renderer, x - 12, y - 12 + i);
        // Top-right corner decoration
        SDL_RenderDrawPointF(renderer, x + totalWidth + 12 - i, y - 12);
        SDL_RenderDrawPointF(renderer, x + totalWidth + 12, y - 12 + i);
        // Bottom-left corner decoration
        SDL_RenderDrawPointF(renderer, x - 12 + i, y + totalHeight + 12);
        SDL_RenderDrawPointF(renderer, x - 12, y + totalHeight + 12 - i);
        // Bottom-right corner decoration
        SDL_RenderDrawPointF(renderer, x + totalWidth + 12 - i, y + totalHeight + 12);
        SDL_RenderDrawPointF(renderer, x + totalWidth + 12, y + totalHeight + 12 - i);
    }
    
    // Calculate total width of the text for alignment
    float totalTextWidth = m_text.length() * (CHAR_WIDTH + CHAR_SPACING) * m_scale;
    
    // Calculate starting x position based on alignment with 2px left adjustment
    float startX = x - 2.0f;  // Move 2 pixels to the left
    if (m_textAlignment > 0.0f) {
        startX = x + (m_width - totalTextWidth) * m_textAlignment - 2.0f;  // Adjust for alignment and move left
    }
    // Add a small vertical offset to center the text better
    const float verticalOffset = 8.0f * (m_scale / 6.0f);
    
    // Draw each character with alignment
    for (size_t i = 0; i < m_text.length(); ++i) {
        // Shadow
        drawChar(renderer, m_text[i], 
                startX + i * (CHAR_WIDTH + CHAR_SPACING) * m_scale + 2, 
                y + 2 + verticalOffset, // Apply vertical offset to shadow
                m_scale,
                {0, 0, 0, 128});
                
        // Main text with pulsing effect
        float pulse = m_effectEnabled ? (std::sin(m_effectTime * 2.0f) * 0.1f + 0.9f) : 1.0f;
        Uint8 red = static_cast<Uint8>(m_color.r * pulse);
        Uint8 green = static_cast<Uint8>(m_color.g * pulse * 0.8f);
        Uint8 blue = static_cast<Uint8>(m_color.b * pulse * 0.6f);
        
        drawChar(renderer, m_text[i], 
                startX + i * (CHAR_WIDTH + CHAR_SPACING) * m_scale, 
                y + verticalOffset, // Apply vertical offset to main text
                m_scale,
                {red, green, blue, m_color.a});
    }
}

void Sign::drawChar(SDL_Renderer* renderer, char c, float x, float y, float scale, const Color& color) const {
    // Convert character to uppercase and get font index
    c = toupper(c);
    int charIndex = (c >= ' ' && c <= '}') ? (c - ' ') : 0;
    
    // Make sure the character index is within bounds
    const int numChars = sizeof(FONT) / (sizeof(uint8_t) * 7);
    if (charIndex < 0 || charIndex >= numChars) {
        charIndex = 0;  // Default to space if character not found
    }
    
    // Draw each pixel of the character
    for (int row = 0; row < CHAR_HEIGHT; ++row) {
        uint8_t rowData = FONT[charIndex][row];
        
        for (int col = 0; col < CHAR_WIDTH; ++col) {
            if (rowData & (1 << (4 - col))) {  // Check each bit from left to right
                // Add a simple pulsing effect
                float pulse = m_effectEnabled ? (sinf(m_effectTime * 3.0f + row * 0.5f) * 0.3f + 0.7f) : 1.0f;
                
                SDL_SetRenderDrawColor(renderer, 
                    static_cast<Uint8>(color.r * pulse), 
                    static_cast<Uint8>(color.g * pulse), 
                    static_cast<Uint8>(color.b * pulse), 
                    color.a);
                    
                SDL_Rect pixel = {
                    static_cast<int>(x + col * scale),
                    static_cast<int>(y + row * scale),
                    static_cast<int>(scale),
                    static_cast<int>(scale)
                };
                SDL_RenderFillRect(renderer, &pixel);
            }
        }
    }
}
